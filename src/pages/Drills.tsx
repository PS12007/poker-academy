import { Suspense, type CSSProperties } from 'react';
import { Link, useParams } from 'react-router-dom';
import { DRILLS, findDrill } from '../trainers/registry';
import { useStore } from '../store';
import { PageHeader } from '../components/ui/primitives';
import { pct } from '../lib/format';
import { Loading } from '../App';
import NotFound from './NotFound';

export function DrillPage() {
  const { drillId } = useParams();
  const drill = findDrill(drillId ?? '');
  if (!drill?.component) return <NotFound />;
  const Drill = drill.component;
  const ready = DRILLS.filter((d) => d.component);
  const i = ready.indexOf(drill);
  return (
    <div>
      <PageHeader serial={drill.serial} kicker="Drill" title={drill.title} lede={drill.blurb} />
      <Suspense fallback={<Loading />}>
        <Drill />
      </Suspense>
      <nav className="mt-16 flex items-center justify-between border-t border-bone/20 pt-5" aria-label="Other drills">
        {i > 0 ? <Link className="btn btn-sm" to={`/drills/${ready[i - 1].id}`}>← {ready[i - 1].title}</Link> : <span />}
        <Link className="btn btn-ghost btn-sm" to="/drills">All drills</Link>
        {i < ready.length - 1 ? <Link className="btn btn-sm" to={`/drills/${ready[i + 1].id}`}>{ready[i + 1].title} →</Link> : <span />}
      </nav>
    </div>
  );
}

export default function Drills() {
  const trainers = useStore((s) => s.trainers);
  return (
    <div>
      <PageHeader
        serial="03"
        kicker="Drills"
        title={<>Endless, <span className="italic text-madder">scored.</span></>}
        lede="Every round is generated by the engine from a seed, so no two sessions repeat and any round can be reproduced. Accuracy, streaks and response time are kept in this browser."
      />
      <ol className="border-t border-bone/30">
        {DRILLS.map((d, i) => {
          const s = trainers[d.id];
          const row = (
            <>
              <span className="label w-12 shrink-0 pt-2 text-madder">{d.serial}</span>
              <span className="min-w-0 flex-1">
                <span className="flex items-baseline gap-3">
                  <span className="display text-[28px] transition-all group-hover:italic group-hover:text-madder sm:text-[38px]">{d.title}</span>
                  <span className="leader hidden sm:block" />
                  <span className="num hidden shrink-0 text-[11px] text-dim sm:block">
                    {!d.component ? 'in preparation' : s?.rounds ? `${pct(s.correct / s.rounds, 0)} over ${s.rounds} · best streak ${s.bestStreak}` : 'not played yet'}
                  </span>
                </span>
                <span className="mt-1 block max-w-[70ch] text-[14px] text-dim">{d.blurb}</span>
              </span>
            </>
          );
          return (
            <li key={d.id} className="rise border-b border-bone/15" style={{ '--i': i } as CSSProperties}>
              {d.component ? <Link to={`/drills/${d.id}`} className="group flex gap-4 py-5">{row}</Link> : <div className="flex gap-4 py-5 opacity-45">{row}</div>}
            </li>
          );
        })}
      </ol>
    </div>
  );
}
