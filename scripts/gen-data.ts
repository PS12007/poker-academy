/**
 * Generates engine-computed data that is too slow to compute on every page
 * load. Output goes to src/generated/ and is committed. Every file records the
 * method, sample size and seed so the numbers can be reproduced: npm run gen
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { monteCarloEquity, rangeSpec } from '../src/engine/equity';
import { HAND_CLASSES } from '../src/engine/ranges';

mkdirSync('src/generated', { recursive: true });

// ------------------------------------------------------------------ hand order
// All-in equity of each of the 169 starting hands against one random hand.
{
  const TRIALS = 400_000;
  const SEED = 1;
  const random = rangeSpec('random');
  const t0 = Date.now();
  const rows = HAND_CLASSES.map((h) => {
    const r = monteCarloEquity({
      game: 'holdem',
      players: [{ hands: h.combos.map(([a, b]) => [a, b]) }, random],
      board: [],
      iterations: TRIALS,
      seed: SEED + h.index,
    });
    return { index: h.index, name: h.name, equity: r.players[0].equity, se: r.players[0].se! };
  });
  const order = [...rows].sort((a, b) => b.equity - a.equity);
  const eq = rows.map((r) => Math.round(r.equity * 10000) / 10000);
  const maxSe = Math.max(...rows.map((r) => r.se));
  writeFileSync(
    'src/generated/handOrder.ts',
    `// GENERATED by scripts/gen-data.ts. Do not edit.
// Monte Carlo, ${TRIALS.toLocaleString('en-US')} trials per hand, seed ${SEED} + class index. Largest standard error ${(maxSe * 100).toFixed(3)}%.

/** Equity of each starting hand class against one random hand, indexed by class index. */
export const EQUITY_VS_RANDOM: readonly number[] = ${JSON.stringify(eq)};

/** Class indices sorted from strongest to weakest by that equity. */
export const HAND_ORDER: readonly number[] = ${JSON.stringify(order.map((r) => r.index))};

export const HAND_ORDER_META = { method: 'Monte Carlo', trials: ${TRIALS}, seed: ${SEED}, maxStandardError: ${maxSe.toFixed(6)} } as const;
`,
  );
  console.log(`handOrder: ${order.slice(0, 6).map((r) => r.name).join(' ')} ... ${order.slice(-3).map((r) => r.name).join(' ')}  (${Date.now() - t0} ms)`);
}
