// Simulates a deploy that removes an old chunk while a tab is open.
import { chromium } from '@playwright/test';
import { readdirSync, renameSync } from 'node:fs';
const base = 'http://localhost:4173/';
const file = readdirSync('dist/assets').find((f) => /^Drills-.*\.js$/.test(f));
const browser = await chromium.launch();
const page = await browser.newPage();
let loads = 0;
page.on('load', () => loads++);
await page.goto(base);
await page.waitForTimeout(1500);
renameSync(`dist/assets/${file}`, `dist/assets/${file}.bak`);
await page.locator('header nav[aria-label="Primary"] a', { hasText: 'Drills' }).first().click();
await page.waitForTimeout(3000);
const text = (await page.locator('main').innerText()).trim();
console.log('page loads:', loads, '| main text:', text.slice(0, 90).replace(/\s+/g, ' '));
renameSync(`dist/assets/${file}.bak`, `dist/assets/${file}`);
await page.reload();
await page.waitForTimeout(1500);
console.log('after restoring the file:', (await page.locator('main').innerText()).trim().slice(0, 60).replace(/\s+/g, ' '));
await browser.close();
