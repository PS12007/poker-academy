/**
 * Generates the 169 x 169 preflop all-in equity matrix used by the push/fold solver.
 * Monte Carlo, a fixed number of trials per pair of hand classes, seeded.
 * Output: src/generated/equity169.ts (base64 of a Uint16 matrix, equity x 65535).
 *
 * Run with: npx tsx scripts/gen-equity169.ts   (about two minutes)
 */
import { writeFileSync } from 'node:fs';
import { evaluate7 } from '../src/engine/evaluator7';
import { HAND_CLASSES } from '../src/engine/ranges';
import { Rng } from '../src/engine/rng';

const TRIALS = 24_000;
const SEED = 169;
const N = 169;
const rng = new Rng(SEED);
const out = new Uint16Array(N * N);
const used = new Uint8Array(52);
const t0 = Date.now();

for (let a = 0; a < N; a++) {
  for (let b = a; b < N; b++) {
    const ca = HAND_CLASSES[a].combos, cb = HAND_CLASSES[b].combos;
    let sum = 0, n = 0;
    while (n < TRIALS) {
      const [a1, a2] = ca[rng.int(ca.length)];
      const [b1, b2] = cb[rng.int(cb.length)];
      if (a1 === b1 || a1 === b2 || a2 === b1 || a2 === b2) continue;
      used[a1] = used[a2] = used[b1] = used[b2] = 1;
      const bd = [0, 0, 0, 0, 0];
      for (let k = 0; k < 5; k++) {
        let c = rng.int(52);
        while (used[c]) c = rng.int(52);
        used[c] = 1;
        bd[k] = c;
      }
      const ra = evaluate7(a1, a2, bd[0], bd[1], bd[2], bd[3], bd[4]);
      const rb = evaluate7(b1, b2, bd[0], bd[1], bd[2], bd[3], bd[4]);
      sum += ra > rb ? 1 : ra === rb ? 0.5 : 0;
      used[a1] = used[a2] = used[b1] = used[b2] = 0;
      for (let k = 0; k < 5; k++) used[bd[k]] = 0;
      n++;
    }
    const e = sum / n;
    out[a * N + b] = Math.round(e * 65535);
    out[b * N + a] = Math.round((1 - e) * 65535);
  }
}

const b64 = Buffer.from(out.buffer).toString('base64');
writeFileSync(
  'src/generated/equity169.ts',
  `// GENERATED by scripts/gen-equity169.ts. Do not edit.
// Preflop all-in equity of every starting hand class against every other.
// Monte Carlo, ${TRIALS.toLocaleString('en-US')} trials per pair, seed ${SEED}. Standard error per cell at most ${(50 / Math.sqrt(TRIALS)).toFixed(2)} points.

export const EQUITY169_META = { method: 'Monte Carlo', trialsPerPair: ${TRIALS}, seed: ${SEED} } as const;

const B64 = '${b64}';

/** Decodes to a Float32Array of 169 x 169 equities: index a * 169 + b is the equity of class a against class b. */
export function loadEquity169(): Float32Array {
  const bin = atob(B64);
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  const u16 = new Uint16Array(bytes.buffer);
  const out = new Float32Array(u16.length);
  for (let i = 0; i < u16.length; i++) out[i] = u16[i] / 65535;
  return out;
}
`,
);
console.log(`equity169: ${N * N} cells, ${TRIALS} trials per pair, ${((Date.now() - t0) / 1000).toFixed(0)} s, AA v KK ${(out[0 * N + 14] / 65535).toFixed(4)}`);
