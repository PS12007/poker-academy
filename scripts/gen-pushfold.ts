/**
 * Precomputes heads-up push/fold Nash charts for common stack depths, so drills
 * can use them without solving in the browser. Run: npx tsx scripts/gen-pushfold.ts
 */
import { writeFileSync } from 'node:fs';
import { solvePushFold } from '../src/engine/pushFold';
import { loadEquity169 } from '../src/generated/equity169';

const STACKS = [3, 4, 5, 6, 7, 8, 9, 10, 12, 15, 20];
const ITER = 4000;
const E = loadEquity169();
const charts: Record<number, { jam: number[]; call: number[]; exploitability: number }> = {};
for (const s of STACKS) {
  const r = solvePushFold(E, { stack: s, iterations: ITER });
  charts[s] = {
    jam: Array.from(r.jam, (x) => Math.round(x * 100) / 100),
    call: Array.from(r.call, (x) => Math.round(x * 100) / 100),
    exploitability: Math.round(r.exploitability * 1e5) / 1e5,
  };
  console.log(`${s}bb: jam ${(r.jamFraction * 100).toFixed(1)}%, call ${(r.callFraction * 100).toFixed(1)}%, exploitability ${r.exploitability.toFixed(5)}`);
}
writeFileSync(
  'src/generated/pushFoldCharts.ts',
  `// GENERATED by scripts/gen-pushfold.ts. Do not edit.
// Heads-up push/fold Nash equilibrium, no ante. Fictitious play, ${ITER} iterations per stack, using src/generated/equity169.ts.

export interface PushFoldChart {
  /** Jam frequency for each of the 169 hand classes, small blind. */
  jam: number[];
  /** Call frequency for each hand class, big blind facing a jam. */
  call: number[];
  /** bb per hand a best response could gain. */
  exploitability: number;
}

export const PUSH_FOLD_STACKS = ${JSON.stringify(STACKS)} as const;
export const PUSH_FOLD_CHARTS: Record<number, PushFoldChart> = ${JSON.stringify(charts)};
`,
);
